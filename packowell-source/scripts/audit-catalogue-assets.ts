/**
 * Read-only audit of the catalogue image library.
 *
 * Enumerates every product in the catalogue and reports what imagery actually
 * exists on disk for it. Writes a markdown table so the finding is reviewable,
 * and exits non-zero when any product has no approved thumbnail (which is the
 * state the catalogue is in until assets are generated).
 *
 *   bun run scripts/audit-catalogue-assets.ts
 */
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { FAMILIES, PRODUCTS, familyById } from '../src/lib/catalog'
import { MANIFEST, type CatalogueAsset } from '../src/lib/catalogue-assets'
import { RIGHTS } from '../src/lib/catalogue-rights'

const PUBLIC = path.resolve(import.meta.dir, '../public')

/** Every image the catalogue currently references, from the manifest. */
const bySlug = new Map<string, CatalogueAsset[]>()
for (const asset of MANIFEST) {
  const list = bySlug.get(asset.productId) ?? []
  list.push(asset)
  bySlug.set(asset.productId, list)
}

interface Finding {
  slug: string
  name: string
  family: string
  thumb: string
  views: string
  missing: string
  source: string
  status: string
}

const rows: Finding[] = []
const hashOwners = new Map<string, string[]>()
const broken: string[] = []
const unapproved: string[] = []

for (const p of PRODUCTS) {
  const assets = bySlug.get(p.slug) ?? []
  const present: CatalogueAsset[] = []
  for (const asset of assets) {
    const abs = path.join(PUBLIC, asset.path)
    if (!existsSync(abs)) {
      broken.push(`${p.slug}: ${asset.path} referenced but missing on disk`)
      continue
    }
    const buf = readFileSync(abs)
    const digest = createHash('sha256').update(buf).digest('hex')
    const owners = hashOwners.get(digest) ?? []
    owners.push(`${p.slug}/${asset.role}`)
    hashOwners.set(digest, owners)
    present.push(asset)
    if (asset.approvalStatus !== 'approved') unapproved.push(`${p.slug}/${asset.role}`)
  }

  const thumb = present.find((a) => a.role === 'thumbnail')
  const detail = present.filter((a) => a.role !== 'thumbnail')
  rows.push({
    slug: p.slug,
    name: p.name,
    family: familyById(p.family).name,
    thumb: thumb ? thumb.path : '— none —',
    views: detail.map((d) => d.role).join(', ') || '—',
    missing: [
      !thumb ? 'thumbnail' : null,
      detail.length === 0 ? 'detail view' : null,
    ]
      .filter(Boolean)
      .join(', ') || 'none',
    source: RIGHTS.find((r) => r.productId === p.slug)?.source ?? '— none —',
    status: thumb?.approvalStatus ?? 'unpublished',
  })
}

const dupes = [...hashOwners.entries()].filter(([, owners]) => owners.length > 1)

const withThumb = rows.filter((r) => r.thumb !== '— none —').length
const withDetail = rows.filter((r) => r.views !== '—').length

const table = [
  '| Product ID | Name | Family | Current thumbnail | Detail views | Missing views | Source | Status |',
  '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| \`${r.slug}\` | ${r.name} | ${r.family} | ${r.thumb} | ${r.views} | ${r.missing} | ${r.source} | ${r.status} |`,
  ),
].join('\n')

console.log(`products: ${PRODUCTS.length} across ${FAMILIES.length} families`)
console.log(`with thumbnail: ${withThumb}/${PRODUCTS.length}`)
console.log(`with detail view: ${withDetail}/${PRODUCTS.length}`)
console.log(`manifest records: ${MANIFEST.length}`)
console.log(`broken references: ${broken.length}`)
console.log(`unapproved assets in use: ${unapproved.length}`)
console.log(`duplicate image files: ${dupes.length}`)
for (const b of broken) console.log(`  BROKEN ${b}`)
for (const u of unapproved) console.log(`  UNAPPROVED ${u}`)
for (const [hash, owners] of dupes) console.log(`  DUPLICATE ${hash.slice(0, 12)} → ${owners.join(' = ')}`)

const out = path.resolve(import.meta.dir, '../docs/CATALOGUE-ASSET-AUDIT.md')
const md = `# Catalogue asset audit

Generated by \`scripts/audit-catalogue-assets.ts\`. Read-only: this file is
regenerated, never hand-edited.

- Products: **${PRODUCTS.length}** across ${FAMILIES.length} families
- Products with a thumbnail: **${withThumb}/${PRODUCTS.length}**
- Products with a detail view: **${withDetail}/${PRODUCTS.length}**
- Manifest records: **${MANIFEST.length}**
- Broken references: **${broken.length}**
- Assets in use without approval: **${unapproved.length}**
- Byte-identical duplicate images: **${dupes.length}**

${table}

## Findings

${broken.length ? `### Broken references\n\n${broken.map((b) => `- ${b}`).join('\n')}\n` : '### Broken references\n\nNone.\n'}

${unapproved.length ? `### Unapproved assets in use\n\n${unapproved.map((u) => `- ${u}`).join('\n')}\n` : '### Unapproved assets in use\n\nNone. Every published asset is marked \`approved\`.\n'}

${dupes.length ? `### Duplicates\n\n${dupes.map(([h, o]) => `- \`${h.slice(0, 12)}\` shared by ${o.join(', ')}`).join('\n')}\n` : '### Duplicates\n\nNone. No two products share a byte-identical image.\n'}
`
await Bun.write(out, md)
console.log(`\nwrote ${path.relative(process.cwd(), out)}`)

if (withThumb < PRODUCTS.length || broken.length > 0 || unapproved.length > 0) {
  process.exit(1)
}
