export type Stage = '3d-studio' | 'quote'

export interface Product {
  slug: string
  name: string
  family: FamilyId
  summary: string
  useCases: string[]
  /** id of a parametric structure in the 3D studio */
  structureId?: string
  stage: Stage
  materials: string[]
  finishing: string[]
  /** honest, template-specific limitation shown on the page */
  watchOut: string
  related: string[]
}

